-- NAIJA TASK Platform Ads backend foundation
-- Apply only after reviewing this migration. It does not connect or deploy Flutterwave.
-- Pricing columns intentionally start NULL: an administrator must set actual prices.

alter table public.platform_settings
  add column if not exists ad_dashboard_placement_fee numeric,
  add column if not exists ad_page_placement_fee numeric,
  add column if not exists ad_daily_fee numeric;

alter table public.platform_ads
  alter column active set default false;

-- Let advertisers read their own inactive/pending campaigns without exposing
-- other advertisers' campaigns. Campaign creation and approval stay restricted.
drop policy if exists "Users can view own platform ads" on public.platform_ads;
create policy "Users can view own platform ads"
  on public.platform_ads for select to authenticated
  using (created_by = auth.uid());

create table if not exists public.ad_campaign_payments (
  id uuid primary key default gen_random_uuid(),
  ad_id uuid not null references public.platform_ads(id) on delete cascade,
  payer_user_id uuid not null references auth.users(id) on delete restrict,
  amount numeric not null check (amount >= 0),
  currency text not null default 'NGN',
  status text not null default 'pending'
    check (status in ('pending','paid','failed','cancelled','refunded')),
  payment_reference text unique,
  provider text,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists ad_campaign_payments_ad_id_idx
  on public.ad_campaign_payments(ad_id);
create index if not exists ad_campaign_payments_payer_idx
  on public.ad_campaign_payments(payer_user_id, created_at desc);
create index if not exists ad_campaign_payments_status_idx
  on public.ad_campaign_payments(status, created_at desc);

alter table public.ad_campaign_payments enable row level security;

drop policy if exists "Users can view own ad campaign payments" on public.ad_campaign_payments;
create policy "Users can view own ad campaign payments"
  on public.ad_campaign_payments for select to authenticated
  using (payer_user_id = auth.uid());

drop policy if exists "Admins can view ad campaign payments" on public.ad_campaign_payments;
create policy "Admins can view ad campaign payments"
  on public.ad_campaign_payments for select to authenticated
  using (exists (
    select 1 from public.admin_users a
    where a.user_id = auth.uid() and a.active = true
  ));

-- No authenticated INSERT/UPDATE policy is created. Only trusted server-side
-- payment code should create payment intents or mark them paid.

-- SECURITY DEFINER helper allows public-ad RLS to check payment status
-- without relying on the caller's restricted view of payment rows.
create or replace function public.is_platform_ad_paid(p_ad_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $
  select exists (
    select 1 from public.ad_campaign_payments p
    where p.ad_id = p_ad_id and p.status = 'paid'
  );
$;

revoke all on function public.is_platform_ad_paid(uuid) from public;
grant execute on function public.is_platform_ad_paid(uuid) to authenticated;

-- Restrict the existing active-ad SELECT policy so a campaign is publicly
-- readable only after a trusted backend has marked at least one payment paid.
-- Admins and campaign owners can still inspect unpaid/inactive campaigns.
drop policy if exists "Paid ads only unless owner or active admin" on public.platform_ads;
create policy "Paid ads only unless owner or active admin"
  on public.platform_ads as restrictive for select to authenticated
  using (
    public.is_platform_ad_paid(platform_ads.id)
    or created_by = auth.uid()
    or exists (
      select 1 from public.admin_users a
      where a.user_id = auth.uid() and a.active = true
    )
  );

create table if not exists public.ad_events (
  id bigint generated by default as identity primary key,
  ad_id uuid not null references public.platform_ads(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  event_type text not null check (event_type in ('impression','click')),
  created_at timestamptz not null default now()
);

create index if not exists ad_events_ad_event_created_idx
  on public.ad_events(ad_id, event_type, created_at desc);

alter table public.ad_events enable row level security;

drop policy if exists "Admins can view ad events" on public.ad_events;
create policy "Admins can view ad events"
  on public.ad_events for select to authenticated
  using (exists (
    select 1 from public.admin_users a
    where a.user_id = auth.uid() and a.active = true
  ));

create or replace function public.record_ad_event(p_ad_id uuid, p_event_type text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    return false;
  end if;

  if p_event_type not in ('impression', 'click') then
    return false;
  end if;

  if not exists (
    select 1 from public.platform_ads a
    where a.id = p_ad_id
      and a.active = true
      and (a.start_at is null or a.start_at <= now())
      and (a.end_at is null or a.end_at >= now())
      and exists (
        select 1 from public.ad_campaign_payments p
        where p.ad_id = a.id and p.status = 'paid'
      )
  ) then
    return false;
  end if;

  insert into public.ad_events(ad_id, user_id, event_type)
  values (p_ad_id, auth.uid(), p_event_type);

  return true;
end;
$$;

revoke all on function public.record_ad_event(uuid, text) from public;
grant execute on function public.record_ad_event(uuid, text) to authenticated;

create or replace function public.set_ad_campaign_payment_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists ad_campaign_payments_set_updated_at on public.ad_campaign_payments;
create trigger ad_campaign_payments_set_updated_at
before update on public.ad_campaign_payments
for each row execute function public.set_ad_campaign_payment_updated_at();

